def _yaml_block(text, key):
    """Lines of a top-level YAML mapping/list, without the key line."""
    match = re.search(r"^%s:[ \t]*\n((?:(?:[ \t-].*)?\n)*)" % re.escape(key), text + "\n", re.M)
    return match.group(1) if match else ""


def _yaml_value(block, key):
    match = re.search(r"^[ \t-]*%s:[ \t]*(.+?)[ \t]*$" % re.escape(key), block, re.M)
    return match.group(1).strip("'\"") if match else None


def actual_state(role):
    """What the Hermes profile currently has, read from its files."""
    folder = profile_dir(role)
    if not os.path.isdir(folder):
        return {"exists": False}
    config_text = read_text(os.path.join(folder, "config.yaml"))
    mcp_block = _yaml_block(config_text, "mcp_servers")
    toolsets = _yaml_block(config_text, "platform_toolsets")
    cli_tools = re.search(r"^[ \t]+cli:[ \t]*\n((?:[ \t]+-.*\n)*)", toolsets, re.M)
    block = re.search(re.escape(BEGIN) + r"\n(.*?)\n" + re.escape(END), read_text(os.path.join(folder, "SOUL.md")), re.S)
    registry = tool_registry()
    mcp = {}
    for tool, spec in registry.items():
        if spec.get("kind") == "mcp":
            marker = _fill(spec.get("requires") or spec.get("command", ""))
            mcp[tool] = bool(re.search(r"^[ \t]{1,4}%s:[ \t]*$" % re.escape(tool), mcp_block, re.M)) and marker in mcp_block
    return {
        "exists": True,
        "model": _yaml_value(_yaml_block(config_text, "model"), "default"),
        "fallback": _yaml_value(_yaml_block(config_text, "fallback_providers"), "model"),
        "effort": _yaml_value(_yaml_block(config_text, "agent"), "reasoning_effort"),
        "mcp": mcp,
        "kanban": bool(cli_tools and re.search(r"-[ \t]*kanban[ \t]*$", cli_tools.group(1), re.M)),
        "skills": {tool: os.path.isfile(os.path.join(folder, "skills", tool, "SKILL.md")) for tool, spec in registry.items() if spec.get("skill") or spec.get("kind") == "skill"},
        "key": read_env(os.path.join(folder, ".env")).get(KEY_VAR, ""),
        "soul_hash": hashlib.sha1(block.group(1).encode("utf-8")).hexdigest() if block else None,
    }


def role_differences(department, role, config, env=None):
    """Human-readable list of what `apply` would change for this role. Empty means in sync."""
    spec, actual = config["roles"][role], actual_state(role)
    if not actual["exists"]:
        return ["profile does not exist yet"]
    tools, registry, diffs = spec.get("tools") or [], tool_registry(), []
    if actual["model"] != spec["model"]:
        diffs.append("model is %s, should be %s" % (actual["model"] or "unset", spec["model"]))
    if (actual["fallback"] or "") != (spec.get("fallback") or ""):
        diffs.append("fallback is %s, should be %s" % (actual["fallback"] or "unset", spec.get("fallback") or "none"))
    if actual["effort"] != spec.get("effort", "medium"):
        diffs.append("effort is %s, should be %s" % (actual["effort"] or "unset", spec.get("effort", "medium")))
    for tool, present in actual["mcp"].items():
        if (tool in tools) != present:
            diffs.append("%s tools %s" % (tool, "missing" if tool in tools else "should be removed"))
        if tool in tools and registry[tool].get("skill") and not actual["skills"].get(tool):
            diffs.append("%s skill missing" % tool)
    for tool in tools:
        if (registry.get(tool) or {}).get("kind") == "skill" and not actual["skills"].get(tool):
            diffs.append("%s skill missing" % tool)
    if "kanban" in tools and not actual["kanban"]:
        diffs.append("task board tools not enabled")
    if not guard_installed(profile_dir(role), guard_config(config, role)):
        diffs.append("guard not installed" if role != (config.get("routing") or {}).get("lead") else "lead guard not installed")
    if actual["soul_hash"] != hashlib.sha1(soul_block(department, role, config).encode("utf-8")).hexdigest():
        diffs.append("role rules out of date")
    wanted_key = key_for(role, department, env)
    if wanted_key and actual["key"] != wanted_key:
        diffs.append("API key not written to the profile" if not actual["key"] else "API key in the profile is not the configured one")
    return diffs


def dispatcher_running():
    try:
        out = subprocess.run(["pgrep", "-fl", "hermes"], capture_output=True, text=True, timeout=10).stdout
    except (OSError, subprocess.TimeoutExpired):
        return None
    return any(re.search(r"hermes\S* (kanban daemon|gateway)\b", line) for line in out.splitlines())


