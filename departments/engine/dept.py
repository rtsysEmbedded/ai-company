def load_models(refresh=False, max_age=24 * 3600):
    """Return {"fetched_at", "models": {id: info}}. Uses the cache when it is fresh or the network fails."""
    cached = read_json(MODELS_CACHE)
    if cached and not refresh and time.time() - cached.get("fetched_at", 0) < max_age:
        return cached
    try:
        request = urllib.request.Request(MODELS_URL, headers={"User-Agent": "ai-company-departments"})
        with urllib.request.urlopen(request, timeout=30) as response:
            raw = json.loads(response.read().decode("utf-8"))
        models = {m["id"]: _simplify(m) for m in raw.get("data", []) if m.get("id")}
        if not models:
            raise ValueError("empty model list")
    except (urllib.error.URLError, OSError, ValueError) as exc:
        if cached:
            cached["stale_reason"] = "Could not refresh from OpenRouter (%s); showing the list from %s" % (
                exc, time.strftime("%Y-%m-%d %H:%M", time.localtime(cached.get("fetched_at", 0))))
            return cached
        return {"fetched_at": 0, "models": {}, "stale_reason": "Could not reach OpenRouter: %s" % exc}
    result = {"fetched_at": int(time.time()), "source": MODELS_URL, "models": models}
    os.makedirs(os.path.dirname(MODELS_CACHE), exist_ok=True)
    with open(MODELS_CACHE, "w", encoding="utf-8") as handle:
        json.dump(result, handle)
    return result


