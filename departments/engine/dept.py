def validate(name, config, models=None):
    """Return (errors, warnings). `models` is the OpenRouter list (id -> info) when available."""
    errors, warnings = [], []
    if not isinstance(config, dict) or not isinstance(config.get("roles"), dict) or not config["roles"]:
        return ["department.json needs a non-empty 'roles' object"], warnings
    roles, routing, registry = config["roles"], config.get("routing") or {}, tool_registry()
    if not str(config.get("projects_dir") or "").strip():
        errors.append("projects_dir is required")
    taken = names_in_use(name)
    for role, spec in roles.items():
        where = "role %s" % role
        if not NAME_RE.match(role):
            errors.append("%s: names are lowercase letters, digits and '-', starting with a letter" % where)
        if role in taken:
            errors.append("%s: that name is already used by %s" % (where, taken[role]))
        if role == name or role in list_departments():
            errors.append("%s: a role cannot have the same name as a department" % where)
        if not isinstance(spec, dict):
            errors.append("%s must be an object" % where)
            continue
        for field in ("title", "description", "model"):
            if not str(spec.get(field) or "").strip():
                errors.append("%s: '%s' is required" % (where, field))
        for field in ("model", "fallback"):
            value = spec.get(field)
            if value and not MODEL_RE.match(str(value)):
                errors.append("%s: %s %r does not look like 'vendor/model'" % (where, field, value))
        if spec.get("fallback") and spec.get("fallback") == spec.get("model"):
            warnings.append("%s: the fallback is the same model as the primary" % where)
        if spec.get("effort", "medium") not in EFFORTS:
            errors.append("%s: effort must be one of %s" % (where, ", ".join(EFFORTS)))
        unknown = [t for t in spec.get("tools") or [] if t not in registry]
        if unknown:
            errors.append("%s: unknown tools %s (allowed: %s)" % (where, ", ".join(unknown), ", ".join(registry)))
        if models and spec.get("enabled", True):
            for field in ("model", "fallback"):
                model_id = spec.get(field)
                if not model_id:
                    continue
                info = models.get(model_id)
                if info is None:
                    warnings.append("%s: %s %s is not in OpenRouter's current model list" % (where, field, model_id))
                    continue
                if not info.get("tools"):
                    errors.append("%s: %s %s does not support tool calling, so it cannot use tools or the task board" % (where, field, model_id))
                for need, label in (("image", "see images"), ("pdf", "read PDF files")):
                    if need in (spec.get("needs") or []) and not info.get(need) and field == "model":
                        warnings.append("%s: %s cannot %s, which this role needs" % (where, model_id, label))
    enabled = [n for n, s in roles.items() if isinstance(s, dict) and s.get("enabled", True)]
    lead = routing.get("lead")
    if lead not in enabled:
        errors.append("routing.lead must name an enabled role (got %r)" % (lead,))
    elif "kanban" not in (roles[lead].get("tools") or []):
        errors.append("the lead role %s needs the 'kanban' tool to hand out tasks" % lead)
    review = routing.get("review", "changes")
    if review not in REVIEW_MODES:
        errors.append("routing.review must be one of %s" % ", ".join(REVIEW_MODES))
    elif review != "off" and routing.get("reviewer") not in enabled:
        errors.append("routing.reviewer must name an enabled role while review is on (got %r)" % (routing.get("reviewer"),))
    try:
        seconds(routing.get("task_timeout", "60m"))
    except ConfigError as exc:
        errors.append(str(exc))
    return errors, warnings


def new_department(name, title, prefix):
    """Create departments/<name>/ from the template, with roles <prefix>-lead, -specialist, -review."""
    if not NAME_RE.match(name or "") or name in RESERVED:
        raise ConfigError("A department name is lowercase letters, digits and '-', starting with a letter")
    if not re.match(r"^[a-z][a-z0-9]{0,7}$", prefix or ""):
        raise ConfigError("The prefix is 1 to 8 lowercase letters or digits, starting with a letter (for example 'rs')")
    if not str(title or "").strip():
        raise ConfigError("A title is required")
    if os.path.exists(department_dir(name)):
        raise ConfigError("A department named %r already exists" % name)
    template = os.path.join(DEPTS, "_template")
    if not os.path.isfile(os.path.join(template, "department.json")):
        raise ConfigError("The template folder departments/_template is missing")
    taken = names_in_use(None)
    clash = [r for r in ("%s-lead" % prefix, "%s-specialist" % prefix, "%s-review" % prefix) if r in taken]
    if clash:
        raise ConfigError("The prefix %r is taken: %s already exists" % (prefix, ", ".join(clash)))
    target = department_dir(name)

    def fill(text):
        return text.replace("{{name}}", name).replace("{{title}}", title.strip()).replace("{{prefix}}", prefix)

    for folder, _, files in os.walk(template):
        relative = os.path.relpath(folder, template)
        os.makedirs(os.path.join(target, fill(relative)) if relative != "." else target, exist_ok=True)
        for filename in files:
            destination = os.path.join(target, fill(os.path.join(relative, filename)) if relative != "." else fill(filename))
            with open(destination, "w", encoding="utf-8") as handle:
                handle.write(fill(read_text(os.path.join(folder, filename))))
    errors, _ = validate(name, load_config(name))
    if errors:
        shutil.rmtree(target, ignore_errors=True)
        raise ConfigError("The template produced an invalid department: " + "; ".join(errors))
    return target


