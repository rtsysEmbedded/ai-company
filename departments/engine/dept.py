# --- small helpers --------------------------------------------------------------
def hermes_home():
    return os.path.expanduser(os.environ.get("HERMES_HOME") or "~/.hermes")


def hermes_bin():
    local = os.path.expanduser("~/.local/bin/hermes")
    return shutil.which("hermes") or (local if os.path.isfile(local) else None)


def profile_dir(name):
    return os.path.join(hermes_home(), "profiles", name)


def data_home():
    return os.path.expanduser(os.environ.get("XDG_DATA_HOME") or "~/.local/share")


def run_hermes(args, answer=None, timeout=180):
    """Run the hermes CLI. Returns (exit_code, output)."""
    binary = hermes_bin()
    if not binary:
        return 127, "hermes was not found on PATH"
    try:
        proc = subprocess.run([binary] + list(args), input=(answer + "\n") if answer else None,
                              stdin=None if answer else subprocess.DEVNULL, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return 124, "hermes %s timed out" % " ".join(args[:3])
    return proc.returncode, (proc.stdout + proc.stderr).strip()


def seconds(duration):
    match = re.fullmatch(r"(\d+)([smhd]?)", str(duration).strip())
    if not match:
        raise ConfigError("task_timeout must look like 45m, 2h or 3600, got %r" % (duration,))
    return int(match.group(1)) * {"": 1, "s": 1, "m": 60, "h": 3600, "d": 86400}[match.group(2)]


def read_text(path):
    try:
        with open(path, "r", encoding="utf-8") as handle:
            return handle.read()
    except OSError:
        return ""


def read_json(path, default=None):
    try:
        with open(path, "r", encoding="utf-8") as handle:
            return json.load(handle)
    except (OSError, ValueError):
        return default


# --- the tools a role can be given ------------------------------------------------
def tool_registry():
    return read_json(os.path.join(ENGINE, "tools.json"), {})


def _fill(text, role=""):
    python = os.environ.get("DEPT_PYTHON") or shutil.which("python3") or sys.executable
    return (text.replace("{python}", python).replace("{data_home}", data_home())
            .replace("{base}", BASE).replace("{role}", role))


def tool_available(tool):
    spec = tool_registry().get(tool) or {}
    if spec.get("kind") == "skill":
        return bool(skill_source(tool))
    return spec.get("kind") != "mcp" or os.path.exists(_fill(spec.get("requires", "")))


def skill_source(tool):
    path = (tool_registry().get(tool) or {}).get("skill")
    for candidate in (os.path.join(BASE, path) if path else None, os.path.join(hermes_home(), "skills", tool, "SKILL.md")):
        if candidate and os.path.isfile(candidate):
            return candidate
    return None


def copy_skill(role, tool, log=print):
    """Copy a tool's SKILL.md into the role's profile."""
    source = skill_source(tool)
    if not source:
        log("  warning: no %s skill found to copy" % tool)
        return
    target = os.path.join(profile_dir(role), "skills", tool)
    os.makedirs(target, exist_ok=True)
    shutil.copyfile(source, os.path.join(target, "SKILL.md"))


# --- .env files -----------------------------------------------------------------
def read_env(path):
    values = {}
    for line in read_text(path).splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            key, value = line.split("=", 1)
            values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def set_env_value(path, key, value):
    """Set or (with value None) remove one variable, keeping every other line. File mode 600."""
    lines = [line for line in read_text(path).splitlines() if not line.startswith(key + "=")]
    if value is not None:
        lines.append("%s=%s" % (key, value))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + ("\n" if lines else ""))
    os.chmod(path, 0o600)


def key_var(scope=None):
    """Variable name for the shared key (no scope), a department's key, or a role's key."""
    return KEY_VAR if not scope else "%s_%s" % (KEY_VAR, scope.upper().replace("-", "_"))


def key_for(role, department, env=None):
    """The most specific key that is set: the role's own, then the department's, then the shared one."""
    env = read_env(ENV_PATH) if env is None else env
    return env.get(key_var(role)) or env.get(key_var(department)) or env.get(KEY_VAR) or ""


def key_source(role, department, env=None):
    """Which key a role uses: 'role', 'department', 'shared' or None. Never the value."""
    env = read_env(ENV_PATH) if env is None else env
    for label, scope in (("role", role), ("department", department), ("shared", None)):
        if env.get(key_var(scope)):
            return label
    return None


def sync_keys(department, config):
    """Write each existing profile's key so it matches departments/.env right away. Returns how many changed.

    Removing the last key that applies to a role also removes it from that role's profile.
    """
    env, changed = read_env(ENV_PATH), 0
    for role, spec in config["roles"].items():
        path = os.path.join(profile_dir(role), ".env")
        if not spec.get("enabled", True) or not os.path.isdir(profile_dir(role)):
            continue
        wanted, current = key_for(role, department, env), read_env(path).get(KEY_VAR, "")
        if wanted != current:
            set_env_value(path, KEY_VAR, wanted or None)
            changed += 1
    return changed


def key_sources():
    """Places an existing OpenRouter key could be imported from. Labels only, never values."""
    sources = []
    if read_env(os.path.join(hermes_home(), ".env")).get(KEY_VAR):
        sources.append({"id": "hermes", "label": "Main Hermes profile (%s)" % os.path.join(hermes_home(), ".env")})
    if os.environ.get(KEY_VAR):
        sources.append({"id": "environment", "label": "Environment variable %s" % KEY_VAR})
    return sources


def import_key(source_id, scope=None):
    if source_id == "hermes":
        value = read_env(os.path.join(hermes_home(), ".env")).get(KEY_VAR)
    elif source_id == "environment":
        value = os.environ.get(KEY_VAR)
    else:
        raise ConfigError("Unknown key source %r" % source_id)
    if not value:
        raise ConfigError("That source has no %s" % KEY_VAR)
    set_env_value(ENV_PATH, key_var(scope), value)


# --- departments ----------------------------------------------------------------
def department_dir(name):
    return os.path.join(DEPTS, name)


def config_path(name):
    return os.path.join(department_dir(name), "department.json")


def list_departments():
    if not os.path.isdir(DEPTS):
        return []
    return sorted(n for n in os.listdir(DEPTS)
                  if NAME_RE.match(n) and n not in RESERVED and os.path.isfile(config_path(n)))


def load_config(name):
    if not NAME_RE.match(name or "") or name in RESERVED:
        raise ConfigError("Unknown department %r" % (name,))
    path = config_path(name)
    try:
        with open(path, "r", encoding="utf-8") as handle:
            return json.load(handle)
    except OSError:
        raise ConfigError("There is no department %r (expected %s). Departments: %s" % (name, path, ", ".join(list_departments()) or "none"))
    except ValueError as exc:
        raise ConfigError("%s is not valid JSON: %s" % (path, exc))


def save_config(name, config):
    errors, _ = validate(name, config)
    if errors:
        raise ConfigError("; ".join(errors))
    path = config_path(name)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as handle:
        json.dump(config, handle, indent=2)
        handle.write("\n")
    os.replace(tmp, path)


def software_roles():
    """Profile names the software department uses (read from its team.yaml without a YAML library)."""
    names, inside = ["default"], False
    for line in read_text(SOFTWARE_TEAM).splitlines():
        if re.match(r"^roles:\s*$", line):
            inside = True
        elif inside and re.match(r"^\S", line):
            inside = False
        elif inside:
            match = re.match(r"^  ([\w-]+):\s*$", line)
            if match:
                names.append(match.group(1))
    return names


def names_in_use(except_department):
    """Role names taken by the software department or by other departments -> who owns them."""
    owners = {n: "the software department" for n in software_roles()}
    for other in list_departments():
        if other != except_department:
            for role in (read_json(config_path(other), {}) or {}).get("roles", {}):
                owners[role] = "the %s department" % other
    return owners


def software_lead():
    """The software team's lead (team.yaml `routing: lead:`), or None when the manager leads that team itself."""
    inside = False
    for line in read_text(SOFTWARE_TEAM).splitlines():
        if re.match(r"^routing:\s*$", line):
            inside = True
        elif inside and re.match(r"^\S", line):
            inside = False
        elif inside:
            match = re.match(r"^  lead:\s*([\w-]+)", line)
            if match:
                return match.group(1) if match.group(1) in software_roles()[1:] else None
    return None


# --- the lead guard: a Hermes hook that keeps a lead from doing its specialists' work on a board task ---------
GUARD_SCRIPT = os.path.join(ENGINE, "lead_guard.py")


def guard_hook(lead=True):
    """The hooks.pre_tool_call entry for a profile: a lead's guard sees every tool call, a specialist's only its board calls."""
    python = os.environ.get("DEPT_PYTHON") or shutil.which("python3") or sys.executable
    return {"matcher": ".*" if lead else "kanban_.*", "command": "%s %s" % (python, GUARD_SCRIPT), "timeout": 10}


def guard_config(config, role):
    """The guard's settings for one role: the team for the lead, the reviewer to name for everyone else."""
    routing = config.get("routing") or {}
    if role == routing.get("lead"):
        return guard_team(config)
    return {"specialist": role, "reviewer": routing.get("reviewer") if routing.get("review", "changes") != "off" else ""}


def guard_team(config):
    """What the guard tells the lead when it refuses a step: who is in the team and which tools they have."""
    lead = (config.get("routing") or {}).get("lead")
    return {"lead": lead, "team": [{"name": n, "title": s.get("title") or n, "tools": tool_names(s)}
                                   for n, s in config["roles"].items() if n != lead and s.get("enabled", True)]}


def guard_installed(folder, team):
    return (GUARD_SCRIPT in read_text(os.path.join(folder, "config.yaml"))
            and read_json(os.path.join(folder, "lead_guard.json"), None) == team)


