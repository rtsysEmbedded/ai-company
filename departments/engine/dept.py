def soul_block(department, role, config):
    spec = config["roles"][role]
    projects = os.path.expanduser(config["projects_dir"])
    folder = department_dir(department)
    parts = ["# Your role: %s (%s), %s department" % (spec["title"], role, config.get("name", department)),
             spec["description"].strip()]
    policies = os.path.join(folder, "policies")
    files = [os.path.join(policies, f) for f in sorted(os.listdir(policies)) if f.endswith(".md")] if os.path.isdir(policies) else []
    for path in files + [os.path.join(folder, "roles", role + ".md")]:
        text = read_text(path).strip()
        if text:
            parts.append(text.replace("{projects_dir}", projects))
    parts.append(routing_rules(role, config))
    parts.append(tools_rules(role, config))
    registry = tool_registry()
    parts.extend(registry[t]["rules"] for t in spec.get("tools") or [] if (registry.get(t) or {}).get("rules"))
    return "\n\n".join(parts)


def _strip_blocks(text):
    """SOUL.md without any generated block (current or from earlier versions)."""
    text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), "", text, flags=re.S)
    for begin, end in OLD_MARKERS:
        text = re.sub(re.escape(begin) + r".*?" + re.escape(end), "", text, flags=re.S)
    return text.strip()


def write_soul(role, block):
    path = os.path.join(profile_dir(role), "SOUL.md")
    base = _strip_blocks(read_text(path)) or BASE_SOUL
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("%s\n\n%s\n%s\n%s\n" % (base, BEGIN, block, END))


