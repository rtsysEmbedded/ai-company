def test_model(model_id, key):
    """Send a 1-token request to check that the key works and the model answers. Returns (ok, message)."""
    if not key:
        return False, "No OpenRouter key is set"
    body = json.dumps({"model": model_id, "max_tokens": 1, "messages": [{"role": "user", "content": "Reply with OK"}]}).encode("utf-8")
    request = urllib.request.Request(CHAT_URL, data=body, headers={
        "Authorization": "Bearer " + key, "Content-Type": "application/json", "User-Agent": "ai-company-departments"})
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            answer = json.loads(response.read().decode("utf-8"))
        if answer.get("error"):
            return False, str(answer["error"].get("message") or answer["error"])
        return True, "%s answered" % (answer.get("model") or model_id)
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", "replace")
        try:
            detail = json.loads(detail)["error"]["message"]
        except (ValueError, KeyError, TypeError):
            detail = detail[:200]
        return False, "HTTP %d: %s" % (exc.code, detail)
    except (urllib.error.URLError, OSError, ValueError) as exc:
        return False, "Could not reach OpenRouter: %s" % exc


