def status(department, config):
    env = read_env(ENV_PATH)
    roles = {}
    for role, spec in config["roles"].items():
        enabled = spec.get("enabled", True)
        roles[role] = {
            "enabled": enabled, "exists": actual_state(role)["exists"], "has_key": bool(key_for(role, department, env)),
            "key_source": key_source(role, department, env),
            "differences": role_differences(department, role, config, env) if enabled else [],
        }
    report = environment_status()
    report.update({
        "department": department,
        "key": {"shared": bool(env.get(KEY_VAR)), "department": bool(env.get(key_var(department))), "sources": report.pop("key_sources")},
        "projects_dir": os.path.expanduser(config["projects_dir"]),
        "roles": roles,
        "in_sync": all(not r["differences"] for r in roles.values() if r["enabled"]),
    })
    return report


# --- apply ----------------------------------------------------------------------
def apply(department, config, only=None, dry_run=False, log=print):
    """Make the Hermes profiles match the department's configuration. Returns True when nothing failed."""
    errors, warnings = validate(department, config, load_models().get("models") or None)
    for warning in warnings:
        log("warning: %s" % warning)
    if errors:
        for error in errors:
            log("error: %s" % error)
        return False
    if not hermes_bin():
        log("error: hermes was not found. Install Hermes Agent first (see departments/README.md).")
        return False
    env, registry = read_env(ENV_PATH), tool_registry()
    ok = True
    prefix = "[dry run] " if dry_run else ""

    def hermes(args, answer=None, what=""):
        nonlocal ok
        code, out = run_hermes(args, answer)
        if code != 0:
            ok = False
            log("  FAILED %s: %s" % (what or " ".join(args[:4]), out[-300:]))
        return code == 0

    for role, spec in config["roles"].items():
        if only and role not in only:
            continue
        if not spec.get("enabled", True):
            log("%s%s: disabled, skipped%s" % (prefix, role, " (its profile still exists)" if os.path.isdir(profile_dir(role)) else ""))
            continue
        before = role_differences(department, role, config, env)
        if not before:
            log("%s%s: already in sync" % (prefix, role))
            continue
        log("%s%s: %s" % (prefix, role, "; ".join(before)))
        if dry_run:
            continue
        if not os.path.isdir(profile_dir(role)):
            create = ["profile", "create", role, "--description", spec["description"]]
            if os.environ.get("DEPT_NO_ALIAS"):  # tests: do not create the launcher scripts
                create.append("--no-alias")
            if not hermes(create, what="create profile"):
                continue
        tools = spec.get("tools") or []
        p = ["-p", role]
        provider = config.get("provider", "openrouter")
        hermes(p + ["config", "set", "model.default", spec["model"]], what="set model")
        hermes(p + ["config", "set", "model.provider", provider], what="set provider")
        hermes(p + ["config", "set", "agent.reasoning_effort", spec.get("effort", "medium")], what="set effort")
        fallback = [{"provider": provider, "model": spec["fallback"]}] if spec.get("fallback") else []
        hermes(p + ["config", "set", "fallback_providers", json.dumps(fallback)], what="set fallback")
        # A model that repeats the same failing tool call is stopped; on its own it can go on for hundreds of calls.
        hermes(p + ["config", "set", "tool_loop_guardrails.hard_stop_enabled", "true"], what="set the loop stop")
        if "kanban" in tools:
            hermes(p + ["tools", "enable", "kanban"], what="enable task board tools")
        is_lead = role == (config.get("routing") or {}).get("lead")
        hermes(p + ["config", "set", "hooks.pre_tool_call", json.dumps([guard_hook(is_lead)])], what="install the guard")
        hermes(p + ["config", "set", "hooks_auto_accept", "true"], what="accept the guard")
        with open(os.path.join(profile_dir(role), "lead_guard.json"), "w", encoding="utf-8") as handle:
            json.dump(guard_config(config, role), handle, indent=1)
        actual = actual_state(role)
        for tool, present in actual["mcp"].items():
            tool_spec, wanted = registry[tool], tool in tools
            if wanted and not tool_available(tool):
                ok = False
                log("  FAILED %s tools: not installed on this machine. %s" % (tool, tool_spec.get("install_hint", "")))
                continue
            if wanted and not present:
                run_hermes(p + ["mcp", "remove", tool], answer="y")  # clear a stale entry, if any
                command = p + ["mcp", "add", tool, "--command", _fill(tool_spec["command"], role)]
                if tool_spec.get("connect_timeout"):
                    command += ["--connect-timeout", str(tool_spec["connect_timeout"])]
                if tool_spec.get("env"):
                    command += ["--env"] + ["%s=%s" % (k, _fill(v, role)) for k, v in tool_spec["env"].items()]
                if tool_spec.get("args"):
                    command += ["--args"] + [_fill(a, role) for a in tool_spec["args"]]   # --args must come last
                # "y" answers Hermes's prompt to enable the discovered tools.
                hermes(command, answer="y", what="add %s tools" % tool)
            elif not wanted and present:
                hermes(p + ["mcp", "remove", tool], answer="y", what="remove %s tools" % tool)
            if wanted and tool_spec.get("skill"):
                copy_skill(role, tool, log)
        for tool in tools:
            if registry[tool].get("kind") == "skill":   # a skill on its own, without an MCP server
                copy_skill(role, tool, log)
        write_soul(role, soul_block(department, role, config))
        key = key_for(role, department, env)
        if key:
            set_env_value(os.path.join(profile_dir(role), ".env"), KEY_VAR, key)
        hermes(["profile", "describe", role, "--overwrite", "--text", spec["description"]], what="set description")
        left = role_differences(department, role, config, env)
        if left:
            ok = False
            log("  still differs after apply: %s" % "; ".join(left))
        else:
            log("  done")
    if not dry_run and not any(key_for(r, department, env) for r in config["roles"]):
        log("note: no OpenRouter key is set for this department, so its agents cannot call a model yet.")
    return ok


def remove(config, log=print):
    ok = True
    for role in config["roles"]:
        if os.path.isdir(profile_dir(role)):
            code, out = run_hermes(["profile", "delete", "-y", role])
            log("%s: %s" % (role, "deleted" if code == 0 else "FAILED: " + out[-200:]))
            ok = ok and code == 0
    return ok


def overview():
    """One line of facts per department, for the list command and the web interface."""
    items = []
    for name in list_departments():
        try:
            config = load_config(name)
            report = status(name, config)
            enabled = [r for r in report["roles"].values() if r["enabled"]]
            items.append({"name": name, "title": config.get("name", name), "roles": len(config["roles"]), "enabled": len(enabled),
                          "lead": (config.get("routing") or {}).get("lead"), "in_sync": report["in_sync"],
                          "has_key": bool(enabled) and all(r["has_key"] for r in enabled),
                          "roles_with_key": sum(1 for r in enabled if r["has_key"])})
        except ConfigError as exc:
            items.append({"name": name, "title": name, "error": str(exc)})
    return items


