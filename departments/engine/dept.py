#!/usr/bin/env python3
"""Department engine for Hermes Agent.

A department is a folder under departments/ holding department.json (roles, models, routing),
roles/<role>.md and policies/*.md. This engine turns each role into a Hermes profile: model,
fallback, tools, skills, API key and role rules. Departments differ only in their files, so a new
department (research, sales, ...) is a new folder, not new code.

Standard library only. Everything that changes Hermes goes through the `hermes` CLI, except three
plain-text files per profile that Hermes documents as user-editable: SOUL.md, .env and skills/.

Usage: dept.py <command>
  list                          the departments and their state
  status [DEPARTMENT] [--json]  what is configured and what Hermes actually has
  validate [DEPARTMENT]         check the configuration
  apply [DEPARTMENT] [--dry-run] [--only ROLE ...]
  new NAME --title TITLE --prefix PREFIX    create a department from the template
  models [--refresh]            fetch OpenRouter's model list
  remove DEPARTMENT [--yes]     delete that department's Hermes profiles
"""
